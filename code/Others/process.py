# 四、各阶段具体操作与检查标准
# -----------------------------------------------------------------------------
# 步骤 01：建立数据清单及方法口径
# 输入：四份核心 CSV、数据包 README 和 DATA_DICTIONARY。
# 操作：记录来源、下载/提取版本、行数、日期范围、字段、单位和缺失情况。
#       将目标样本、试运行样本、原论文口径与现行官方口径分别注明。
#       财务历史筛选、BE 会计规则、证券筛选及权重规则都需写明后固定。
# 检查：输入可读取，所需字段齐全，原始数据保持原样。
#
# 步骤 02：整理官方基准及 RF
# 输入：F-F factors and RF.csv。
# 操作：跳过说明文字，仅保留首字段为六位 YYYYMM 的月度记录，排除年度
#       汇总和页脚；读取 Mkt-RF、SMB、HML、RF，处理源文件缺失代码。
#       所有收益统一为小数：官方文件中的百分数除以 100。
#       提取 200001-202512；官方值只作基准，RF 可作为计算输入。
# 检查：月份唯一、连续，共 312 行；四个收益字段有效且没有未处理缺失。
# 建议输出：官方月度基准表。
#
# 步骤 03：先完成市场因子 MKT-RF
# 输入：monthly_stock.csv 的 MthCalDt、vwretd，以及步骤 02 的 RF。
# 操作：只读所需列，统一月份；确认同月 vwretd 一致后，每月保留一个值。
#       不对重复出现的市场收益求和，也不在股票筛选后才提取市场指数。
#       MKT_RF_CRSP_t = vwretd_t - RF_t。
#       CRSP 收益已是小数，不再除以 100。按月一对一连接官方市场因子。
# 检查：312 个月、每月唯一、没有缺失，检查相关系数、MAE 和最大偏差月。
# 建议输出：month、vwretd、rf、mkt_rf_crsp、mkt_rf_official、difference。
# 方法说明：这是以 CRSP 现成市场指数构造的市场超额收益。vwretd 覆盖范围
#           可能与 French 的美国注册普通股市场组合不同，不能声称完全同口径。
#           如需更严格对齐，后续按官方市场股票范围另算市值加权市场收益，
#           并核对月初分类、价格/股数、月收益及滞后权重信息是否完整。
#           市场组合不受 Compustat 成功匹配和正 BE 条件限制。
#
# 步骤 04：清洗 CRSP 并构造公司市值
# 输入：monthly_stock.csv；大文件按所需列或分块读取。
# 操作：统一日期、标识和数值类型，保留证券历史分类的有效时点。
#       前期检查发现按 PERMNO + MthCalDt 有 29,621 行超出唯一键的记录。
#       核查分红事件或历史记录展开等原因，比较核心股票字段，不能盲目
#       保留第一行，更不能将同一证券月重复计入收益和市值。
#       根据 CIZ 字典确定普通股、交易所、交易状态及交易条件筛选规则，
#       记录每一步剔除数量；不直接套用旧版 share code 字段。
#       保留历史退市公司，不能只保留样本末期仍上市的公司。
#       核实 MthRet 已含的退市收益处理，避免再合并旧版 DLRET 重复调整。
#       计算证券市值 ME = abs(MthPrc) * ShrOut。
#       ShrOut 单位为千股，因此上述 ME 为千美元；BE 为百万美元时要统一。
#       与 MthCap 核对；将同一 PERMCO 多类股票的有效市值汇总到公司层面，
#       明确代表证券与收益的处理规则，避免同一公司账面权益被重复使用。
#       MthPrevCap 必须结合 MthPrevDt 检查是否确为所需上一月的信息。
# 检查：证券月唯一，筛选依据可追溯，权重市值为正且时点正确。
# 建议输出：清洗股票月表、筛选计数表、重复与缺失问题清单。
#
# 步骤 05：计算 Compustat 账面权益 BE
# 输入：Compustat.csv。
# 操作：按数据说明筛选报表格式、合并口径和币种，处理公司年度重复记录。
#       使用 datadate 确定财务报表所属日历年；核查同年多报表和变更会计年度。
#       股东权益 SE：优先 seq；缺失时按明确规则使用 ceq + pstk 或 at - lt。
#       优先股 PS：按 pstkrv、pstkl、pstk 的顺序选取可用值。
#       原论文基本定义：BE = SE + 递延税项及投资税收抵免 - PS。
#       常用字段 txditc 对应递延税项及投资税收抵免；缺失项的替代规则需
#       单独说明，不能把未知的股东权益整体当成零。
#       对照现行 French/WRDS 文档核实递延税项等历史口径变化，注明采用
#       原论文还是现行基准口径，必要时作差异分析，不为贴合结果任意改规则。
#       六组合使用 BE > 0；执行历史记录筛选时，先在完整历史上计算记录年数，
#       再截取分析期，不把研究窗口内首条记录等同于数据库首次出现。
# 检查：账面权益公式、替代顺序、单位、日历年及可用历史长度均明确。
# 建议输出：公司年度 BE 表，保留原始字段、计算口径和数据可用性标记。
#
# 步骤 06：CCM 连接及信息时点控制
# 输入：清洗股票数据、年度 BE 表、CCM.csv。
# 操作：规范 gvkey 与 PERMNO/LPERMNO；按文档选择链接质量及主链接规则，
#       记录选择原因；解析 LINKDT、LINKENDDT，包括结束日期 E 等特殊标记。
#       检查链接在选定匹配时点有效；不能忽略日期，只按 gvkey 直接连接。
#       常用六月形成表以形成日核验链接，并进一步核对历史证券/公司映射。
#       处理一对多和多对一关系，检查合并行数及唯一键，输出未匹配数量。
#       形成年度 t 的六月组合，只使用日历年 t-1 内结束会计年度的 BE。
#       六月滞后安排用于降低前视偏差；若另有实际披露时间，进一步核对。
# 检查：每个公司形成年度的有效匹配可解释，未用未来财务信息填补历史。
# 建议输出：六月形成候选表与匹配覆盖率表。
#
# 步骤 07：计算 BM、NYSE 分界点与六组合标签
# 输入：匹配表、t-1 年十二月公司市值、t 年六月公司市值。
# 操作：BM_t = BE_(会计年度结束于 t-1) / ME_(t-1 年十二月)。
#       Size_t = ME_(t 年六月)。排除必要输入缺失、BE 非正或市值非正记录。
#       依据选定方法明确规模和 BM 各自的 NYSE 分界点参考样本。
#       NYSE 六月规模中位数将股票分为 S（小）、B（大）。
#       NYSE BM 的 30%、70% 分位点将股票分为 L（低）、N（中）、H（高）。
#       分界点应用于符合条件的 NYSE、AMEX、NASDAQ 股票。
#       两种排序独立进行，再取交集：S/L、S/N、S/H、B/L、B/N、B/H。
#       固定并记录分位数算法、相等边界归属，不能在 S/B 内分别重算 BM 分位点。
# 检查：每年三个分界点、六组股票数和市值占比合理；每只股票归属唯一。
# 建议输出：年度分界点表、六月分组表及各组样本数量。
#
# 步骤 08：持有期权重与六组合月收益
# 输入：六月分组、六月市值、股票月度总收益 MthRet 和不含分配收益 MthRetx。
# 操作：t 年六月标签用于 t 年七月至 t+1 年六月，次年六月末重新分组。
#       七月使用六月末公司市值为基准；后续以此前月份 MthRetx 滚动更新
#       持仓权重，明确公司行动、多类股和退市处理，避免当月收益进入当月权重。
#       对代表证券路径，月 m 的未归一权重可写为：
#       W_i,m = ME_i,June * product(1 + RETX_i,k)，k 从七月至 m 的上一月；
#       七月乘积为空，取 1。公司聚合或证券切换须与选定方法保持一致。
#       R_p,m = sum(W_i,m * RET_i,m) / sum(W_i,m)，在同一有效收益样本上求和。
#       明确收益缺失、历史断档及退市后的处理，不能无条件填零或继续持有。
# 检查：每月六组收益有效，组内归一权重和为 1，无负权重及未来信息；
#       若某组为空，则相关因子标缺失并记录原因，不将空组收益设为零。
# 建议输出：六组合月收益、每组股票数和有效权重覆盖情况。
#
# 步骤 09：构造 SMB、HML 并整理三因子
# SMB_m = (R_SL,m + R_SN,m + R_SH,m) / 3
#         - (R_BL,m + R_BN,m + R_BH,m) / 3
# HML_m = (R_SH,m + R_BH,m) / 2 - (R_SL,m + R_BL,m) / 2
# 六组合内部市值加权；上述组合之间按公式等权平均，不能再按组市值加权。
# SMB/HML 已是多空收益差，不再减 RF。
# 将其与步骤 03 的市场因子按月份合并，并保留各因子的可用性标记。
# 检查：手工复核若干月份及六月/七月边界，月份唯一且收益单位一致。
# 建议输出：月度自建三因子表；缺历史数据的月份保持缺失。
#
# 步骤 10：与官方基准比较和定位误差
# 操作：按月份一对一合并，分别使用各因子的共同有效样本；跨因子对照
#       另用共同窗口，并在表图中写清时间和样本数。
#       计算 difference = constructed - official、相关系数、平均误差、
#       MAE = mean(abs(difference))、RMSE = sqrt(mean(difference**2))。
#       检查误差最大的月份，不能只凭高相关系数判定成功。
# 排查顺序：单位/月份 -> 重复数据 -> 筛选/历史链接 -> BE 时点和规则 ->
#           NYSE 分界点 -> 权重/退市 -> 数据版本与市场覆盖范围。
# 可选：下载官方 2×3 六组合收益，帮助确定偏差来自哪一组。
# 检查：不为了获得更高相关系数而使用未来信息或调整样本掩盖差异。
#
# 步骤 11：生成老师要求的统计与图
# 必做：自建与官方三个因子的描述性统计、累计收益图及比较说明。
# 建议统计：月份数、均值、标准差、中位数、最小值、最大值；统一单位。
# 建议比较：相关系数、平均误差、MAE、RMSE，以及月度差异图。
# 每个因子各画一张自建与官方叠加图，共三张累计收益比较图。
# 统一累计公式：C_T = product(1 + f_m) - 1，起点和样本期保持一致。
# 图名注明“因子收益复合累计序列”。市场超额收益的复合序列不等于
# 市场总收益净值；SMB/HML 的复合序列也不代表无需说明融资方式的投资净值。
# 遇到缺失月份先确定连续有效区间，不用自动跳过缺失的方法暗中连接曲线。
# 建议输出：因子统计表、误差表、三张累计图和辅助差异图。
#
# 步骤 12：补充早期数据并完整重跑
# 操作：追加历史数据时记录版本，检查重叠月份是否修订，不静默覆盖冲突。
#       从源数据重新计算 BE 历史筛选、CCM 匹配、年度分组及权重；不是仅在
